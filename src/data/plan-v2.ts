// Exact won arithmetic; rounded display amounts are never used as equalities.
export const toWon = (eok: string) => Math.round(Number(eok) * 100_000_000);
const sumColumn = (rows: string[][], column: number) =>
  rows.reduce((sum, row) => sum + toWon(row[column]), 0);
export const formatEok = (won: number) =>
  (won / 100_000_000).toFixed(3).replace(/0+$/, "").replace(/\.$/, ".0");
